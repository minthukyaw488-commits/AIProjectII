"""
위기(자살·자해 암시) 감지 + 고정 안내 답변.

위기 표현이 있으면 RAG/LLM 에 보내지 않고, 항상 같은 안전 안내(109·129·119)를
바로 보여준다. 작은 모델이 위기 질문에 복지 목록을 늘어놓는 일을 막는다.
오탐(예: '죽어도 못 잊어')보다 미탐이 훨씬 위험하므로 넓게 잡는다.
"""
from __future__ import annotations

# 공백을 지운 문장에서 찾는다("죽고 싶" == "죽고싶").
CRISIS_PATTERNS = (
    "죽고싶", "죽고파", "죽어야", "죽어도되", "죽어도돼", "죽어버리", "죽을래",
    "죽을까", "죽으면", "죽겠어", "살기싫", "살고싶지않", "사는게싫", "그만살",
    "자살", "자해", "목숨을끊", "목숨끊", "사라지고싶", "끝내고싶", "세상을떠나고",
)

CRISIS_REPLY = (
    "많이 힘드시지요. 그 마음을 말씀해 주셔서 고맙습니다. 혼자 견디지 않으셔도 됩니다.\n\n"
    "- 지금 바로 **자살예방 상담전화 109** 로 전화해 주세요. **24시간 · 무료 · 비밀보장**입니다.\n"
    "- 생명이 위급하면 **119** 에 바로 전화하세요.\n"
    "- 복지·생활 상담은 **보건복지상담센터 129** 에서도 도와드립니다.\n\n"
    "괜찮으시다면 지금 어떤 일이 가장 힘드신지 저에게 조금 더 말씀해 주세요. "
    "담당 사회복지사님께도 안부 확인을 요청해 두겠습니다."
)


# 서비스 이름(예: '자살예방 상담 전화번호')은 위기 표현이 아니므로 먼저 지운다.
_NOT_CRISIS = ("자살예방", "자해예방")


def is_crisis(text: str) -> bool:
    t = (text or "").replace(" ", "")
    for w in _NOT_CRISIS:
        t = t.replace(w, "")
    return any(p in t for p in CRISIS_PATTERNS)
