def get_detail(name: str) -> dict | None:
    return DETAILS.get(name)


@lru_cache(maxsize=1)
def _meal_rows() -> list[dict]:
    path = _DOCS / "대전광역시_재가노인 식사배달 현황_20230331.csv"
    for enc in ("cp949", "utf-8-sig"):
        try:
            with open(path, encoding=enc, newline="") as f:
                return list(csv.DictReader(f))
        except (UnicodeDecodeError, OSError):
            continue
    return []


def meal_centers(district: str | None, limit: int = 5) -> list[dict]:
    """대전 재가노인 식사배달 수행기관 — 사는 구가 있으면 그 구만."""
    rows = _meal_rows()
    if district:
        rows = [r for r in rows if f" {district} " in f" {r.get('소재지도로명주소', '')} "]
    return [{"name": r.get("시설명", ""), "phone": r.get("전화번호", ""),
             "addr": r.get("소재지도로명주소", "")} for r in rows[:limit]]
