"""위기(자살·자해) 표현 감지 + 고정 안내 답변 — 앱·파이프라인·이상신호가 함께 쓰는 단일 기준.

왜 따로 두나:
  예전에는 위기 키워드가 config(4개, 띄어쓰기 포함)와 app.py(배너용) 두 곳에 따로 있었고,
  감지돼도 '알림'만 갔을 뿐 답변은 일반 복지 RAG 답변이 나갔다
  (예: "제가 죽어도 되나요?" → 무연고 사망 절차 안내). 위기 표현에는 문서 검색·LLM
  생성을 하지 않고, 항상 같은 '도움 연결' 안내를 즉시 돌려준다.

감지 방식:
  띄어쓰기를 모두 지운 뒤 패턴을 찾는다("죽고 싶" / "죽고싶" 모두 감지).
  '죽' 한 글자처럼 넓은 패턴은 쓰지 않는다(죽 배달·남편이 돌아가셨다 같은 일반 복지
  질문을 막지 않도록). 오탐보다 미탐이 위험하므로, 애매하면 패턴을 추가하는 쪽으로 관리한다.
"""
from __future__ import annotations

# 띄어쓰기 없이 적는다(입력도 띄어쓰기를 지우고 비교).
CRISIS_PATTERNS = (
    # 죽음·자살 의사
    "죽고싶", "죽고파", "죽어버리", "죽어야", "죽어도되", "죽어도괜찮", "죽어도상관",
    "죽을래", "죽을까", "죽고말", "죽는게낫", "죽는편이낫", "죽으면편",
    "자살", "자해",
    # 삶을 끝내려는 표현
    "살기싫", "살고싶지않", "살아서뭐", "살이유가없", "살의미가없",
    "끝내고싶", "끝내버리", "생을마감", "목숨을끊", "세상을떠나고싶",
    "사라지고싶", "없어지고싶",
    # 방법 암시
    "목매", "뛰어내리", "약을다먹", "수면제를모", "농약을먹",
)

CRISIS_REPLY = (
    "말씀해 주셔서 고맙습니다. 지금 많이 힘드신 것 같아 걱정돼요.\n"
    "혼자 견디지 마시고, 지금 바로 도움을 받으세요.\n\n"
    "- **자살예방 상담전화 109** — 24시간 · 무료 · 비밀 보장\n"
    "- 지금 위급하면 **119** (경찰 **112**)\n"
    "- 생활이 어려우시면 **보건복지상담센터 129**\n\n"
    "가까운 가족이나 이웃에게도 꼭 알려 주세요. 담당 사회복지사에게도 알림이 전달됩니다."
)


# 제도·기관 이름 속 '자살'은 위기 표현이 아니다(예: "자살예방센터 어디예요?").
_INFO_TERMS = ("자살예방", "자해예방")


def _norm(text: str) -> str:
    t = "".join((text or "").split())
    for term in _INFO_TERMS:
        t = t.replace(term, "")
    return t


def matched(text: str) -> list[str]:
    """text 에서 찾은 위기 패턴 목록(없으면 빈 리스트)."""
    t = _norm(text)
    return [p for p in CRISIS_PATTERNS if p in t]


def is_crisis(text: str) -> bool:
    """위기(자살·자해) 표현이 있으면 True."""
    t = _norm(text)
    return any(p in t for p in CRISIS_PATTERNS)
